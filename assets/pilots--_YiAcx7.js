<section id="steps" class="detail">
<div class="sh rv">
<p class="eyebrow">From commitment to action</p>
<h2 class="h2">Six steps to a working programme.</h2>
</div>
<ol class="steps grow">
<li>
<span class="sn">01</span>
<div>
<h3>Select the value chain and farmer cohort</h3>
<p>Identify the location, agricultural activity and participating farmers. Define the need the pilot will address.</p>
</div>
</li>
<li>
<span class="sn">02</span>
<div>
<h3>Align governance and accountability</h3>
<p>Name the lead organisations, delivery partners and decision-makers. Make member protection and responsibilities explicit.</p>
</div>
</li>
<li>
<span class="sn">03</span>
<div>
<h3>Mobilise the required capabilities</h3>
<p>Bring together funding, technology, field support, inputs, services, logistics and market relationships appropriate to the scope.</p>
</div>
</li>
<li>
<span class="sn">04</span>
<div>
<h3>Launch a controlled pilot</h3>
<p>Agree service availability, provider arrangements, participant onboarding and the evidence needed before delivery begins.</p>
</div>
</li>
<li>
<span class="sn">05</span>
<div>
<h3>Assess outcomes and economics</h3>
<p>Review delivery performance, farmer participation, transaction evidence and the commercial or programme model.</p>
</div>
</li>
<li>
<span class="sn">06</span>
<div>
<h3>Scale what works</h3>
<p>Use the results to decide whether to improve, repeat or expand the approach across regions or nationally.</p>
</div>
</li>
</ol>
</section>
